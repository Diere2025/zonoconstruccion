-- Copia recuperable de los renglones que antes representaban descuentos.
CREATE TABLE IF NOT EXISTS public.wholesale_discount_item_migration_backup (
  id UUID PRIMARY KEY,
  order_id UUID NOT NULL,
  product_id UUID,
  product_name TEXT,
  quantity NUMERIC,
  unit_price NUMERIC,
  subtotal NUMERIC,
  discount_percentage NUMERIC,
  historical_unit_cost NUMERIC,
  migrated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

INSERT INTO public.wholesale_discount_item_migration_backup
  (id, order_id, product_id, product_name, quantity, unit_price, subtotal, discount_percentage, historical_unit_cost)
SELECT id, order_id, product_id, product_name, quantity, unit_price, subtotal, discount_percentage, historical_unit_cost
FROM public.order_items
WHERE lower(COALESCE(product_name, '')) LIKE '%descuento%'
   OR lower(COALESCE(product_name, '')) LIKE '%bonificaci%'
ON CONFLICT (id) DO NOTHING;

WITH discounts AS (
  SELECT order_id,
         round(sum(abs(COALESCE(subtotal, quantity * unit_price, unit_price, 0))), 2) AS amount
  FROM public.wholesale_discount_item_migration_backup
  GROUP BY order_id
)
UPDATE public.orders o
SET order_discount_type = 'fixed',
    order_discount_value = d.amount,
    order_discount_amount = d.amount,
    totals = COALESCE(o.totals, '{}'::jsonb) || jsonb_build_object(
      'order_discount_type', 'fixed',
      'order_discount_value', d.amount,
      'order_discount_amount', d.amount
    )
FROM discounts d
WHERE o.id = d.order_id;

DELETE FROM public.order_items oi
USING public.wholesale_discount_item_migration_backup b
WHERE oi.id = b.id;

-- Facundo usa AQ-FP para ambos canales: Procedencia manda sobre el prefijo.
UPDATE public.orders o
SET channel = CASE
  WHEN lower(src.name) = 'mayorista' THEN 'mayorista'
  WHEN lower(src.name) LIKE '%orgánico%'
    OR lower(src.name) LIKE '%organico%'
    OR lower(src.name) LIKE '%cliente habitual%'
    OR lower(src.name) LIKE '%recomendado%' THEN 'web_organica'
  ELSE o.channel
END
FROM public.sellers s, public.advertising_sources src
WHERE o.seller_id = s.id
  AND o.advertising_source_id = src.id
  AND lower(s.full_name) = 'facundo paz'
  AND upper(COALESCE(o.legacy_code, '')) LIKE 'AQ-%';

-- Para el resto de los vendedores, los prefijos históricos sí identifican B2B.
UPDATE public.orders o
SET channel = 'mayorista'
WHERE (upper(COALESCE(o.legacy_code, '')) LIKE 'AQ-%'
    OR upper(COALESCE(o.legacy_code, '')) LIKE 'AQU%'
    OR upper(COALESCE(o.legacy_code, '')) LIKE 'POW%')
  AND NOT EXISTS (
    SELECT 1 FROM public.sellers s
    WHERE s.id = o.seller_id AND lower(s.full_name) = 'facundo paz'
  );

-- Vincular pedidos antiguos sin cuenta sólo cuando el nombre identifica una única cuenta.
WITH unique_clients AS (
  SELECT lower(trim(business_name)) AS normalized_name, min(id::text)::uuid AS client_id
  FROM public.clients
  WHERE business_name IS NOT NULL AND trim(business_name) <> ''
  GROUP BY lower(trim(business_name))
  HAVING count(*) = 1
)
UPDATE public.orders o
SET client_id = u.client_id
FROM unique_clients u
WHERE o.client_id IS NULL
  AND o.channel = 'mayorista'
  AND lower(trim(o.customer_name)) = u.normalized_name;

UPDATE public.clients c
SET is_wholesale = true,
    client_type = 'Mayorista'
WHERE EXISTS (
  SELECT 1 FROM public.orders o
  WHERE o.client_id = c.id AND o.channel = 'mayorista'
);

