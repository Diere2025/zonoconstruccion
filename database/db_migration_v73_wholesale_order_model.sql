-- La misma tabla base sirve a Logística; las pantallas trabajan con vistas por canal.
CREATE OR REPLACE VIEW public.v_wholesale_orders
WITH (security_invoker = true) AS
SELECT o.*
FROM public.orders o
WHERE o.channel = 'mayorista';

DROP VIEW IF EXISTS public.v_client_balances_and_stats CASCADE;
CREATE VIEW public.v_client_balances_and_stats
WITH (security_invoker = true) AS
WITH client_orders AS (
  SELECT client_id, COALESCE(sum(total_amount), 0) AS total_charged, count(*) AS orders_count
  FROM public.orders
  WHERE status NOT IN ('Anulado', 'Cancelado')
  GROUP BY client_id
), client_payments_sum AS (
  SELECT client_id, COALESCE(sum(amount * COALESCE(exchange_rate, 1)), 0) AS total_paid
  FROM public.client_payments
  WHERE status = 'Aprobado'
  GROUP BY client_id
)
SELECT c.*,
       COALESCE(o.total_charged, 0) AS total_charged,
       COALESCE(p.total_paid, 0) AS total_paid,
       CASE WHEN c.is_wholesale THEN COALESCE(o.total_charged, 0) - COALESCE(p.total_paid, 0) ELSE 0 END AS balance,
       COALESCE(o.orders_count, 0)::integer AS orders_count
FROM public.clients c
LEFT JOIN client_orders o ON o.client_id = c.id
LEFT JOIN client_payments_sum p ON p.client_id = c.id;

